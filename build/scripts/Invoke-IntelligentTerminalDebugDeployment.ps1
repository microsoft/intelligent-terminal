<#
.SYNOPSIS
Safely deploys an already-built Intelligent Terminal loose Debug package.

.DESCRIPTION
Use this script after a Debug Terminal build produces
CascadiaPackage.build.appxrecipe and the change requires package deployment
(for example C++, XAML, IDL, wtcli, manifest, resource, or mixed changes).

The script targets only the dev-sideload package, verifies that its installed
loose layout is the AppX directory next to the supplied Debug recipe, closes
only processes executing from that layout, runs DeployAppRecipe.exe, and
reopens Intelligent Terminal only when it was running before deployment.
Ordinary Windows Terminal processes are never closed.

This script does not build Terminal or WTA. Do not use it for a change whose
only packaged output is wta.exe; that flow should build and hot-refresh WTA
without redeploying the Terminal package. Deployment terminates all active
Intelligent Terminal panes and agent sessions.

.PARAMETER AppxRecipePath
Path to the CascadiaPackage.build.appxrecipe generated by a Debug build.

.PARAMETER DeployAppRecipePath
Optional explicit path to DeployAppRecipe.exe. When omitted, the script checks
PATH and then the latest Visual Studio installation reported by vswhere.

.PARAMETER NoForce
Fail instead of force-stopping same-package processes that remain after the
graceful-close timeout.

.PARAMETER NoRestart
Leave Intelligent Terminal closed after deployment.

.EXAMPLE
.\build\scripts\Invoke-IntelligentTerminalDebugDeployment.ps1 `
    -AppxRecipePath src\cascadia\CascadiaPackage\bin\x64\Debug\CascadiaPackage.build.appxrecipe
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [Parameter(Mandatory = $true)]
    [string]$AppxRecipePath,

    [string]$DeployAppRecipePath,

    [ValidateRange(1, 60)]
    [int]$CloseTimeoutSeconds = 10,

    [switch]$NoForce,

    [switch]$NoRestart
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$PackageFamilyName = 'IntelligentTerminal_rd9vj3e6a2mbr'
$PackageIdentityName = 'IntelligentTerminal'
$PackageIdentityPublisher = 'CN=Intelligent Terminal Dev'
$ApplicationId = 'App'

function Test-PathWithinDirectory {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path,

        [Parameter(Mandatory = $true)]
        [string]$Directory
    )

    $normalizedPath = [System.IO.Path]::GetFullPath($Path)
    $normalizedDirectory = [System.IO.Path]::GetFullPath($Directory).TrimEnd('\') + '\'
    return $normalizedPath.StartsWith($normalizedDirectory, [System.StringComparison]::OrdinalIgnoreCase)
}

function Get-InstalledTargetPackage {
    $packages = @(Get-AppxPackage | Where-Object { $_.PackageFamilyName -ceq $PackageFamilyName })
    if ($packages.Count -ne 1) {
        if ($packages.Count -eq 0) {
            return $null
        }
        throw "Expected at most one installed package for family '$PackageFamilyName', found $($packages.Count)."
    }
    if ([string]::IsNullOrWhiteSpace($packages[0].InstallLocation)) {
        throw "Package family '$PackageFamilyName' has no install location."
    }

    return $packages[0]
}

function Get-DeployAppRecipePath {
    param(
        [string]$RequestedPath
    )

    if (-not [string]::IsNullOrWhiteSpace($RequestedPath)) {
        return (Resolve-Path $RequestedPath -ErrorAction Stop).Path
    }

    $command = Get-Command 'DeployAppRecipe.exe' -ErrorAction SilentlyContinue
    if ($command) {
        return $command.Source
    }

    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (-not (Test-Path $vswhere -PathType Leaf)) {
        throw 'DeployAppRecipe.exe is not on PATH and vswhere.exe is unavailable.'
    }

    $installationPath = & $vswhere -latest -products * -requires Microsoft.Component.MSBuild -property installationPath
    if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($installationPath)) {
        throw 'vswhere.exe could not find a Visual Studio installation with MSBuild.'
    }

    $candidate = Join-Path $installationPath.Trim() 'Common7\IDE\DeployAppRecipe.exe'
    if (-not (Test-Path $candidate -PathType Leaf)) {
        throw "DeployAppRecipe.exe was not found at '$candidate'."
    }

    return $candidate
}

function Get-AppxRecipeMetadata {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path
    )

    [xml]$recipe = Get-Content $Path -Raw
    $namespace = [System.Xml.XmlNamespaceManager]::new($recipe.NameTable)
    $namespace.AddNamespace('msb', $recipe.DocumentElement.NamespaceURI)

    $readProperty = {
        param([string]$Name)

        $node = $recipe.SelectSingleNode("/msb:Project/msb:PropertyGroup/msb:$Name", $namespace)
        if ($null -eq $node -or [string]::IsNullOrWhiteSpace($node.InnerText)) {
            throw "Appx recipe '$Path' does not define $Name."
        }
        return $node.InnerText.Trim()
    }

    return [pscustomobject]@{
        IdentityName = & $readProperty 'PackageIdentityName'
        Publisher = & $readProperty 'PackageIdentityPublisher'
        LayoutDir = & $readProperty 'LayoutDir'
    }
}

function Get-TargetPackageProcesses {
    param(
        [Parameter(Mandatory = $true)]
        [string]$InstallLocation
    )

    $matches = @()
    foreach ($process in @(Get-Process -ErrorAction SilentlyContinue)) {
        try {
            $processPath = $process.Path
        }
        catch {
            continue
        }

        if ([string]::IsNullOrWhiteSpace($processPath)) {
            continue
        }

        if (Test-PathWithinDirectory -Path $processPath -Directory $InstallLocation) {
            $matches += $process
        }
        elseif ($process.ProcessName -eq 'WindowsTerminal') {
            Write-Verbose "Ignoring WindowsTerminal PID $($process.Id) at '$processPath'."
        }
    }

    return $matches
}

$resolvedRecipePath = (Resolve-Path $AppxRecipePath -ErrorAction Stop).Path
if ($resolvedRecipePath -notmatch '\\Debug\\[^\\]+\.build\.appxrecipe$') {
    throw "This script only accepts a Debug .build.appxrecipe; received '$resolvedRecipePath'."
}

$debugLayout = [System.IO.Path]::GetFullPath((Join-Path (Split-Path $resolvedRecipePath -Parent) 'AppX'))
$recipeMetadata = Get-AppxRecipeMetadata -Path $resolvedRecipePath
if ($recipeMetadata.IdentityName -cne $PackageIdentityName -or
    $recipeMetadata.Publisher -cne $PackageIdentityPublisher) {
    throw "Appx recipe identity '$($recipeMetadata.IdentityName)' / '$($recipeMetadata.Publisher)' is not the Intelligent Terminal dev package."
}

$recipeLayout = [System.IO.Path]::GetFullPath($recipeMetadata.LayoutDir)
if (-not $recipeLayout.Equals($debugLayout, [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "Appx recipe LayoutDir '$recipeLayout' does not match its adjacent Debug AppX directory '$debugLayout'."
}

$package = Get-InstalledTargetPackage
if ($package -and
    -not [System.IO.Path]::GetFullPath($package.InstallLocation).Equals(
        $debugLayout,
        [System.StringComparison]::OrdinalIgnoreCase)) {
    throw "The installed dev package points to '$($package.InstallLocation)', not this recipe's Debug layout '$debugLayout'."
}

$resolvedDeployAppRecipePath = Get-DeployAppRecipePath -RequestedPath $DeployAppRecipePath
$targetProcesses = @(Get-TargetPackageProcesses -InstallLocation $debugLayout)
$targetHostProcesses = @($targetProcesses | Where-Object { $_.ProcessName -eq 'WindowsTerminal' })
$wasRunning = $targetHostProcesses.Count -gt 0
$aumid = "$PackageFamilyName!$ApplicationId"

Write-Host "Target package: $(if ($package) { $package.PackageFullName } else { "$PackageFamilyName (not currently installed)" })"
Write-Host "Debug layout:   $debugLayout"
Write-Host "Deploy tool:    $resolvedDeployAppRecipePath"
Write-Host "Appx recipe:    $resolvedRecipePath"

if ($targetProcesses.Count -gt 0) {
    foreach ($process in $targetProcesses) {
        Write-Host "Matched package process $($process.ProcessName) PID $($process.Id): $($process.Path)"
    }
}
else {
    Write-Host 'No running processes matched the target package.'
}

if ($WhatIfPreference) {
    foreach ($process in $targetProcesses) {
        $null = $PSCmdlet.ShouldProcess("$($process.ProcessName) PID $($process.Id)", 'Close package process before deployment')
    }
    $null = $PSCmdlet.ShouldProcess($resolvedRecipePath, 'Deploy loose Debug package')
    if ($wasRunning -and -not $NoRestart) {
        $null = $PSCmdlet.ShouldProcess($aumid, 'Restart Intelligent Terminal after deployment')
    }
    return
}

if ($targetProcesses.Count -gt 0) {
    foreach ($process in $targetHostProcesses) {
        if ($PSCmdlet.ShouldProcess("Intelligent Terminal PID $($process.Id)", 'Close main window')) {
            $null = $process.CloseMainWindow()
        }
    }

    $deadline = [DateTime]::UtcNow.AddSeconds($CloseTimeoutSeconds)
    $remaining = @(Get-TargetPackageProcesses -InstallLocation $debugLayout)
    while ($remaining.Count -gt 0 -and [DateTime]::UtcNow -lt $deadline) {
        Start-Sleep -Milliseconds 200
        $remaining = @(Get-TargetPackageProcesses -InstallLocation $debugLayout)
    }

    if ($remaining.Count -gt 0) {
        if ($NoForce) {
            $remainingSummary = (($remaining | ForEach-Object { "$($_.ProcessName) PID $($_.Id)" }) -join ', ')
            throw "Target package processes did not exit within $CloseTimeoutSeconds seconds: $remainingSummary."
        }

        foreach ($process in $remaining) {
            if ($PSCmdlet.ShouldProcess("$($process.ProcessName) PID $($process.Id)", 'Force stop package process after close timeout')) {
                Stop-Process -Id $process.Id -Force
            }
        }

        $forceDeadline = [DateTime]::UtcNow.AddSeconds(5)
        do {
            Start-Sleep -Milliseconds 200
            $remaining = @(Get-TargetPackageProcesses -InstallLocation $debugLayout)
        } while ($remaining.Count -gt 0 -and [DateTime]::UtcNow -lt $forceDeadline)

        if ($remaining.Count -gt 0) {
            $remainingSummary = (($remaining | ForEach-Object { "$($_.ProcessName) PID $($_.Id)" }) -join ', ')
            throw "Target package processes are still running after forced shutdown: $remainingSummary."
        }
    }
}

$deploymentError = $null
try {
    if ($PSCmdlet.ShouldProcess($resolvedRecipePath, 'Deploy loose Debug package')) {
        $global:LASTEXITCODE = 0
        & $resolvedDeployAppRecipePath $resolvedRecipePath
        $pipelineSucceeded = $?
        $deploymentExitCode = $global:LASTEXITCODE

        if (-not $pipelineSucceeded -or $deploymentExitCode -ne 0) {
            throw "Deployment failed with exit code $deploymentExitCode."
        }
    }
}
catch {
    $deploymentError = $_
}

$restartError = $null
if ($wasRunning -and -not $NoRestart) {
    try {
        if ($PSCmdlet.ShouldProcess($aumid, 'Restart Intelligent Terminal')) {
            Start-Process 'explorer.exe' -ArgumentList "shell:AppsFolder\$aumid"
        }
    }
    catch {
        $restartError = $_
    }
}

if ($deploymentError) {
    if ($restartError) {
        Write-Error "Intelligent Terminal restart also failed: $($restartError.Exception.Message)"
    }
    throw $deploymentError
}
if ($restartError) {
    throw $restartError
}
